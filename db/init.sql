SET NAMES utf8mb4;

-- Tabel induk: satu baris per kata Indonesia.
CREATE TABLE IF NOT EXISTS kata (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  kata_indonesia VARCHAR(100) NOT NULL,
  kategori VARCHAR(50) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_kata_indonesia (kata_indonesia)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Tabel anak: padanan di bahasa daerah per tingkat kesopanan.
-- Relasi satu kata -> banyak padanan (maksimal satu per tingkat).
-- ON DELETE CASCADE: menghapus kata otomatis menghapus semua padanannya.
CREATE TABLE IF NOT EXISTS padanan (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  kata_id INT UNSIGNED NOT NULL,
  tingkat ENUM('halus', 'sedang', 'akrab') NOT NULL,
  kata_daerah VARCHAR(100) NOT NULL,
  contoh_kalimat VARCHAR(500) NULL,
  catatan VARCHAR(500) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_kata_tingkat (kata_id, tingkat),
  CONSTRAINT fk_padanan_kata FOREIGN KEY (kata_id) REFERENCES kata (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

